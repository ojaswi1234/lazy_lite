#!/usr/bin/env python3
"""
gen_splash_art.py
Generates ASCII art for Lite XL's empty view and terminal splash screen.
Outputs a Lua file: splash_art.lua in the plugins directory.
"""

import pyfiglet
import os
import sys

USERDIR = os.path.join(os.path.expanduser("~"), ".config", "lite-xl")
OUT_LUA  = os.path.join(USERDIR, "plugins", "splash_art.lua")

def escape_lua(s):
    """Escape a string for safe embedding in a Lua long string bracket."""
    # Use Lua level-2 long strings to avoid any escaping issues
    return s

def make_art():
    logo = pyfiglet.figlet_format("Lite  XL", font="slant")
    # Trim trailing whitespace per line but keep blank lines
    lines = [l.rstrip() for l in logo.splitlines()]
    # Remove leading/trailing blank lines
    while lines and lines[0].strip() == "":
        lines.pop(0)
    while lines and lines[-1].strip() == "":
        lines.pop()
    return "\n".join(lines)

def make_terminal_banner():
    logo = pyfiglet.figlet_format("Lite  XL", font="speed")
    lines = [l.rstrip() for l in logo.splitlines()]
    while lines and lines[0].strip() == "":  lines.pop(0)
    while lines and lines[-1].strip() == "": lines.pop()
    banner = "\n".join(lines)
    # Tagline
    tagline = "  The lightweight text editor you will enjoy using."
    divider = "  " + "-" * (max(len(l) for l in lines) - 2)
    return "\n".join([banner, divider, tagline])

SPLASH_ART       = make_art()
TERMINAL_BANNER  = make_terminal_banner()

LUA_TEMPLATE = r"""-- mod-version:3
-- Splash Art: beautiful ASCII art for the empty view & terminal startup
-- Auto-generated by scripts/gen_splash_art.py — do not edit manually.

local core    = require "core"
local style   = require "core.style"
local View    = require "core.view"
local keymap  = require "core.keymap"
local command = require "core.command"

-- ── ASCII art strings ─────────────────────────────────────────────────────────

local SPLASH_ART = [==[
{SPLASH_ART}
]==]

local TERMINAL_BANNER = [==[
{TERMINAL_BANNER}
]==]

-- ── Override EmptyView.draw ───────────────────────────────────────────────────

local EmptyView = require "core.emptyview"
local orig_draw = EmptyView.draw

EmptyView.draw = function(self)
  self:draw_background(style.background)

  local sf = style.code_font or style.font
  local lf = style.font
  local dim = style.dim

  -- split art into lines
  local art_lines = {}
  for l in (SPLASH_ART .. "\n"):gmatch("([^\n]*)\n") do
    table.insert(art_lines, l)
  end
  while #art_lines > 0 and art_lines[#art_lines]:match("^%s*$") do
    table.remove(art_lines)
  end

  local fh = math.floor(sf:get_height() * 1.15)
  local art_h = #art_lines * fh

  -- hint lines
  local hints = {
    { fmt = "%s  run a command",              cmd = "core:find-command" },
    { fmt = "%s  open a file from project",   cmd = "core:find-file" },
    { fmt = "%s  change project folder",      cmd = "core:change-project-folder" },
    { fmt = "%s  open a project folder",      cmd = "core:open-project-folder" },
  }
  local hfh = lf:get_height() + 6
  local hints_h = #hints * hfh + 16

  local total_h = art_h + 20 + hints_h
  local start_y = self.position.y + math.max(0, (self.size.y - total_h) / 2)

  -- measure max art width
  local max_art_w = 0
  for _, l in ipairs(art_lines) do
    local w = sf:get_width(l)
    if w > max_art_w then max_art_w = w end
  end
  local start_x = self.position.x + math.max(style.padding.x, (self.size.x - max_art_w) / 2)

  -- draw ascii art
  local cy = start_y
  for _, l in ipairs(art_lines) do
    renderer.draw_text(sf, l, start_x, cy, dim)
    cy = cy + fh
  end

  cy = cy + 20

  -- divider
  renderer.draw_rect(
    self.position.x + style.padding.x,
    math.floor(cy - 10),
    self.size.x - style.padding.x * 2,
    math.ceil(SCALE),
    { dim[1], dim[2], dim[3], 40 }
  )

  -- hint lines centred
  local max_hint_w = 0
  for _, h in ipairs(hints) do
    local binding = keymap.get_binding(h.cmd) or "?"
    local txt = string.format(h.fmt, binding)
    local w = lf:get_width(txt)
    if w > max_hint_w then max_hint_w = w end
  end
  local hx = self.position.x + math.max(style.padding.x, (self.size.x - max_hint_w) / 2)

  for _, h in ipairs(hints) do
    local binding = keymap.get_binding(h.cmd) or "?"
    local txt = string.format(h.fmt, binding)
    renderer.draw_text(lf, txt, hx, cy, dim)
    cy = cy + hfh
  end
end

-- ── Terminal banner (shown once at startup) ───────────────────────────────────

local _banner_done = false
local TermView = nil
pcall(function() TermView = require "plugins.terminal" end)

local function inject_terminal_banner()
  if _banner_done or not core.active_view then return end
  -- Walk all views, find TermView instances
  local function walk(node)
    if not node then return end
    if node.views then
      for _, v in ipairs(node.views) do
        if TermView and v:is(TermView) and v.terminal then
          if v.terminal.write then
            v.terminal:write("\r\n" .. TERMINAL_BANNER .. "\r\n\r\n")
            _banner_done = true
          end
        end
      end
    end
    if node.a then walk(node.a) end
    if node.b then walk(node.b) end
  end
  pcall(walk, core.root_view.root_node)
end

core.add_thread(function()
  -- Wait a couple of frames so terminal has initialised
  coroutine.yield(0.8)
  inject_terminal_banner()
end)
"""

def main():
    lua = LUA_TEMPLATE \
        .replace("{SPLASH_ART}", SPLASH_ART) \
        .replace("{TERMINAL_BANNER}", TERMINAL_BANNER)

    os.makedirs(os.path.dirname(OUT_LUA), exist_ok=True)
    with open(OUT_LUA, "w", encoding="utf-8") as f:
        f.write(lua)

    print(f"[OK] Written to: {OUT_LUA}")
    print("\n=== Splash Art Preview ===")
    print(SPLASH_ART)
    print("\n=== Terminal Banner Preview ===")
    print(TERMINAL_BANNER)

if __name__ == "__main__":
    main()
