#!/usr/bin/env python3
"""
gen_splash_art.py
Generates rich ASCII art for Lite XL's empty view and terminal splash screen.
  - Empty view  : "Electronic" font  (▄ ▐░▌ half-block style)
  - Terminal    : "banner3-D" font   (##:::::: dot-grid style)
Uses pyfiglet for art generation. Re-run any time to regenerate.
"""

import pyfiglet
import os
import sys
import io

# Force UTF-8 output so box chars don't explode on Windows console
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

USERDIR  = os.path.join(os.path.expanduser("~"), ".config", "lite-xl")
OUT_LUA  = os.path.join(USERDIR, "plugins", "splash_art.lua")

# ── Art generation ─────────────────────────────────────────────────────────────

def trim(lines):
    while lines and not lines[0].strip():  lines.pop(0)
    while lines and not lines[-1].strip(): lines.pop()
    return lines

def art(text, font):
    raw   = pyfiglet.figlet_format(text, font=font)
    return trim([l.rstrip() for l in raw.splitlines()])


def make_splash():
    """
    Rich half-block Electronic logo for the empty editor view.
    We render "Lite" and "XL" separately so the split is cleaner,
    then combine them side-by-side.
    """
    # Electronic renders each word tall — join into one art block
    lines = art("Lite  XL", "Electronic")
    width = max(len(l) for l in lines)

    # Fancy banner above
    banner_text = "─── The Lightweight Text Editor ───"
    pad_left  = (width - len(banner_text)) // 2
    banner    = " " * max(0, pad_left) + banner_text

    result = [banner, ""] + lines
    return "\n".join(result)


def make_terminal_banner():
    """
    Sharp banner3-D logo for the terminal startup.
    Adds double-line borders and a tagline.
    """
    lines = art("Lite  XL", "banner3-D")
    width = max(len(l) for l in lines)

    inner_w = width + 6
    top    = "  " + "╔" + "═" * inner_w + "╗"
    bot    = "  " + "╚" + "═" * inner_w + "╝"
    div    = "  " + "╠" + "═" * inner_w + "╣"
    blank  = "  " + "║" + " " * inner_w + "║"
    sep    = "  " + "║" + "─" * inner_w + "║"

    def row(line):
        padded = "   " + line.ljust(width) + "   "
        return "  ║" + padded + "║"

    tagline   = f"   {'The lightweight text editor — fast, beautiful, yours.':^{inner_w}}   "
    tag_row   = "  ║" + f"{'  The lightweight text editor — fast, beautiful, yours.  ':^{inner_w}}" + "║"
    ver_row   = "  ║" + f"{'  v2.1.8   ·   https://lite-xl.com  ':^{inner_w}}" + "║"

    result = ["", top, blank]
    for l in lines:
        result.append(row(l))
    result.append(blank)
    result.append(div)
    result.append(tag_row)
    result.append(ver_row)
    result.append(bot)
    result.append("")
    return "\n".join(result)


SPLASH_ART      = make_splash()
TERMINAL_BANNER = make_terminal_banner()

